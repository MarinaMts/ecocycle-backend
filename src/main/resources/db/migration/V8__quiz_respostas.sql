-- Respostas da ultima tentativa de cada usuario em cada quiz, para o app
-- mostrar a correcao (o que a pessoa marcou x a alternativa correta) mesmo
-- depois de sair e voltar. Cada novo envio substitui as respostas anteriores.
CREATE TABLE quiz_respostas (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_resultado_id   BIGINT NOT NULL,
    pergunta_id         BIGINT NOT NULL,
    alternativa_id      BIGINT NOT NULL,
    CONSTRAINT uk_quiz_resposta_resultado_pergunta UNIQUE (quiz_resultado_id, pergunta_id),
    CONSTRAINT fk_quiz_resposta_resultado FOREIGN KEY (quiz_resultado_id)
        REFERENCES quiz_resultados (id) ON DELETE CASCADE,
    CONSTRAINT fk_quiz_resposta_pergunta FOREIGN KEY (pergunta_id)
        REFERENCES perguntas (id),
    CONSTRAINT fk_quiz_resposta_alternativa FOREIGN KEY (alternativa_id)
        REFERENCES alternativas (id)
);

CREATE INDEX idx_quiz_resposta_resultado ON quiz_respostas (quiz_resultado_id);
